/* main/security/fido_attest.h — certificat et cle d'attestation U2F, generes.
 *
 * U2F EXIGE une attestation X.509 dans la reponse a U2F_REGISTER (voir
 * contraintes-globales.md, ecart assume 3 : la spec CTAP2 tranche
 * « attestation none », ce qui n'existe pas en U2F). Un certificat
 * auto-signe est ce que font les implementations libres et ce que les
 * navigateurs acceptent pour une attestation « basic ».
 *
 * Regenere par :
 *
 *   openssl ecparam -genkey -name prime256v1 -out /tmp/attest.key
 *   openssl req -new -x509 -key /tmp/attest.key -days 7300 -sha256 \
 *     -subj "/CN=Niphargus FIDO Attestation" -outform DER -out /tmp/attest.der
 *   xxd -i /tmp/attest.der
 *
 * (`xxd -i` nomme le tableau d'apres le chemin du fichier temporaire ; les
 * symboles ci-dessous sont renommes a la main en fido_attest_cert_der/
 * fido_attest_cert_len, meme convention que main/hmi/screen_logo.h.)
 *
 * La cle privee ci-dessous (fido_attest_key, le scalaire brut extrait de
 * /tmp/attest.key par `openssl ec -in /tmp/attest.key -text -noout`) EST
 * COMMITEE EN CLAIR DANS LE FIRMWARE, DELIBEREMENT : U2F_REGISTER exige une
 * signature PAR la cle d'attestation (Ruling 2, tache 7) ; le brief initial
 * n'exportait que le certificat, avec lequel on ne peut pas signer.
 *
 * CETTE CLE N'A AUCUNE VALEUR DE SECRET. Elle est PARTAGEE PAR TOUS LES
 * EXEMPLAIRES de cette carte — c'est exactement ce que signifie une
 * attestation « basic » (par opposition a une attestation « per-credential »
 * ou chaque carte aurait sa propre cle) : elle atteste du MODELE
 * d'authentificateur, pas d'un exemplaire. Un attaquant qui l'extrairait
 * d'une carte ne gagnerait rien qu'il n'ait deja en lisant ce fichier source.
 * Ne JAMAIS la confondre avec K_maitre (fido_master.c, en NVS, propre a
 * chaque carte, elle protege reellement des credentials) ni la faire
 * grossir en pretention de secret qu'elle n'a pas.
 */
